#' Summary plot of an object of class \code{meantobvs}
#'
#' Plots to summarize graphically the results in an object of class
#' \code{meantobvs}, including prior and posterior probabilities obtained.
#'
#' Two summaries are available: the model size probability if \code{plotdim}=TRUE
#' and the inclusion probabilities if  \code{plotpip}=TRUE. By default,
#' both plots are shown.
#'
#' @export
#' @param meantobvs.object Object of class \code{meantobvs}.
#' @param plotdim Logical indicating whether or not to plot model dimension
#' probabilities.
#' @param plotpip Logical indicating whether or not to plot posterior inclusion
#' probabilities.
#' @param ... Additional graphical parameters.
#'
#' @author Carolina Mulet
#' Maintainer: <carolina.mulet1@@alu.uclm.es>
#'
#' @seealso See \code{\link[meantobvs]{bvs.lm}}, \code{\link[meantobvs]{bvs.glm}},
#' \code{\link[meantobvs]{gibbsbvs.lm}} and \code{\link[meantobvs]{gibbsbvs.glm}}
#' for creating objects of class \code{meantobvs}.
#'
#' @examples
#' #Cross-Country Growth, from Fernández, Ley and Steel (2001)
#' data("dataS97")
#'
#' # Here we keep the eight models generated by three candidate covariates:
#' f <- gr56092 ~ 1 + lifee060 + gdpsh60l + p60
#' dataS97.meantobvs <- bvs.lm(
#'   formula = f, data = dataS97, n.keep = 8, n.imp = 2, imp.seed = 1
#' )
#'
#' # Show both summaries, only inclusion probabilities, or only model sizes:
#' plot(dataS97.meantobvs)
#' plot(dataS97.meantobvs, plotdim = FALSE)
#' plot(dataS97.meantobvs, plotpip = FALSE)

plot.meantobvs <- function(meantobvs.object, plotdim = TRUE, plotpip = TRUE, ...) {

  if (!inherits(meantobvs.object, "meantobvs")){
    warning("An object of class meantobvs is needed.\n")
  }

  p <- meantobvs.object$p #number of covariates
  k <- meantobvs.object$k #number of fixed vars
  vars <- meantobvs.object$variables

  #save previous adjustment
  oldpar <- par(no.readonly = TRUE)

  par(mar = c(5, 4, 4, 2) + 0.1, mfrow = c(plotdim + plotpip, 1))
  if (plotdim) {

    #dimension probabilities
    if (meantobvs.object$method == "gibbs") {
      main.1 <- "Estimated Model Size Probabilities"
    } else main.1 <- "Model Size Probabilities"

    barplot(
      meantobvs.object$priorprobs,
      main = main.1, names.arg = (0:p) + k,
      xlab = "Number of covariates in the true model",
      ylab = "Probability",
      col = "lightsteelblue1",
      border = NA, ylim = c(0, 1), las = 1,
      cex.names =0.8, cex.axis = 0.8, cex.lab = 0.8,
      ...
    )
    par(new = TRUE)
    barplot(
      meantobvs.object$postprobdim,
      col = "lightsteelblue4",
      border = NA,
      ylim = c(0, 1),
      cex.names = 0.8,
      axes = FALSE,
      ...
    )
    abline(h = seq(0,1,0.2), col = "gray90", lty = "dotted")

    legend(
      "topright",
      legend = c("Posterior", "Prior"),
      fill = c("lightsteelblue4", "lightsteelblue1"),
      border = NA,
      bty = "n"
    )
  }

  if (plotpip) {

    #posterior inclusion probabilities
    if (meantobvs.object$method == "gibbs") {
      main.2 <- "Estimated Posterior Inclusion Probabilities"
    } else main.2 <- "Posterior Inclusion Probabilities"

    barplot(
      meantobvs.object$inclprob,
      main = main.2, names.arg = vars,
      col = "lightsteelblue4",
      border = NA,
      ylim = c(0, 1),
      las = 2,
      cex.names = 0.8, cex.axis = 0.8, cex.lab = 0.8,
      ylab = "Probability",
      ...
    )
    abline(h = 0.5, col = "lightsteelblue1", lty = 2, lwd = 2)
    abline(h = seq(0,1,0.2), col = "gray90", lty = "dotted")
  }

  par(mar = oldpar$mar, mfrow = oldpar$mfrow) #return to original values
}
